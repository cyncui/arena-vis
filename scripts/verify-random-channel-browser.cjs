const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.argv[2] || 'http://localhost:3101';
const output = process.env.AUDIT_OUTPUT || '/tmp/arena-vis-random';
fs.mkdirSync(output, { recursive: true });
let browser;
(async () => {
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base, { waitUntil: 'networkidle' });
  const family = await page.locator('.landing-subtitle').evaluate(el => getComputedStyle(el).fontFamily);
  assert(family.startsWith('"Open Runde",'), family);
  await page.evaluate(() => document.fonts.ready);
  const cdp = await page.context().newCDPSession(page);
  await cdp.send('DOM.enable');
  await cdp.send('CSS.enable');
  const { root } = await cdp.send('DOM.getDocument');
  const { nodeId } = await cdp.send('DOM.querySelector', { nodeId: root.nodeId, selector: '.landing-subtitle' });
  const { fonts } = await cdp.send('CSS.getPlatformFontsForNode', { nodeId });
  assert(fonts.some(font => /Open Runde/i.test(font.familyName) && font.isCustomFont), JSON.stringify(fonts));
  await page.waitForTimeout(900);
  await page.screenshot({ path: path.join(output, 'runde-landing.png') });
  const graphData = { nodes: [{ id: 'channel-1', name: 'sample followed channel', type: 'channel', val: 30, channelData: { id: 1, slug: 'sample-followed', title: 'sample followed channel', length: 1 } }, { id: 'block-2', name: 'sample text', type: 'block', val: 20, blockData: { id: 2, type: 'Text', content: 'sample text' } }], links: [{ source: 'channel-1', target: 'block-2' }] };
  let graphRequests = 0;
  let randomRequests = 0;
  let errorResponse = false;
  await page.route('**/api/arena?*', route => { graphRequests++; return route.fulfill({ json: { graphData } }); });
  await page.route('**/api/random-channel', async route => {
    randomRequests++;
    await new Promise(resolve => setTimeout(resolve, 250));
    return route.fulfill(errorResponse ? { status: 404, json: { error: 'no followed channels found for this profile.' } } : { json: { channel: { slug: 'sample-followed', title: 'sample followed channel' } } });
  });
  await page.goto(`${base}/explore`, { waitUntil: 'networkidle' });
  const random = page.getByRole('button', { name: /^random$/i });
  await random.click();
  assert(await random.isDisabled(), 'random is disabled during lookup');
  assert(await page.getByRole('button', { name: /^explore$/i }).isDisabled(), 'explore is disabled during lookup');
  await page.getByRole('status').waitFor();
  await page.waitForURL('**slug=sample-followed');
  await page.locator('.scene-container canvas').waitFor();
  await page.waitForTimeout(1000);
  assert.equal(await page.locator('form input').inputValue(), 'sample-followed');
  assert.equal(graphRequests, 1, 'random navigation loads the graph once');
  await random.click();
  await page.waitForTimeout(750);
  assert.equal(graphRequests, 2, 'same-slug random reloads once');
  errorResponse = true;
  await random.click();
  const alert = page.getByRole('alert').filter({ hasText: 'no followed channels found for this profile.' });
  await alert.waitFor();
  assert.equal(await alert.textContent(), 'no followed channels found for this profile.');
  assert.equal(graphRequests, 2, 'failed random selection retains the current graph');
  assert.equal(await page.locator('.scene-container canvas').count(), 1);
  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({ width, height: 844 });
    await page.waitForTimeout(800);
    const randomBox = await random.boundingBox();
    const controlsBox = await page.getByRole('button', { name: /^controls$/i }).boundingBox();
    const inputBox = await page.locator('form input').boundingBox();
    const overlap = randomBox.x < controlsBox.x + controlsBox.width && randomBox.x + randomBox.width > controlsBox.x && randomBox.y < controlsBox.y + controlsBox.height && randomBox.y + randomBox.height > controlsBox.y;
    assert(!overlap, `random and controls do not overlap at ${width}`);
    assert(inputBox.width > 60 && randomBox.x >= 0 && randomBox.x + randomBox.width <= width, `search remains usable at ${width}`);
    await page.screenshot({ path: path.join(output, `random-${width}.png`) });
  }
  await page.goto(base, { waitUntil: 'networkidle' });
  await page.waitForTimeout(900);
  await page.screenshot({ path: path.join(output, 'runde-mobile.png') });
  assert.equal(errors.length, 0, errors.join('\n'));
  fs.writeFileSync(path.join(output, 'result.json'), JSON.stringify({ passed: true, family, fonts, randomRequests, graphRequests, errors }, null, 2));
  console.log('open runde font and random channel browser checks passed');
  await browser.close();
})().catch(async error => { console.error(error); if (browser) await browser.close(); process.exitCode = 1; });
